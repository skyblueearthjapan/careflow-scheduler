function pyb_writeAssignmentResults_(ss, tz, assignments) {
  var sheet = ss.getSheetByName('割当結果');
  if (!sheet) {
    sheet = ss.insertSheet('割当結果');
  }

  // Clear and write header
  sheet.clear();
  var headers = ['visit_id', '日付', '曜日', 'staff_id', 'スタッフ名', 'patient_id', '患者名', 'エリア', '開始時刻', '終了時刻', 'サービス時間', '時間タイプ', '希望最早時刻', '希望最遅時刻', '備考'];
  sheet.getRange(1, 1, 1, headers.length).setValues([headers]);

  if (assignments.length === 0) return;

  var rows = [];
  for (var i = 0; i < assignments.length; i++) {
    var a = assignments[i];
    var dateVal = a.date ? pyb_parseDate_(a.date) : '';
    rows.push([
      a.visit_id || '',
      dateVal || a.date || '',
      a.weekday || '',
      a.staff_id || '',
      a.staff_name || '',
      a.patient_id || '',
      a.patient_name || '',
      a.area || '',
      a.start_time_minutes != null ? a.start_time_minutes / 1440 : '',
      a.end_time_minutes != null ? a.end_time_minutes / 1440 : '',
      a.service_minutes || '',
      a.time_type || '',
      a.earliest_time_minutes != null ? a.earliest_time_minutes / 1440 : '',
      a.latest_time_minutes != null ? a.latest_time_minutes / 1440 : '',
      a.notes || ''
    ]);
  }

  sheet.getRange(2, 1, rows.length, headers.length).setValues(rows);
}

function pyb_writeUnassigned_(ss, tz, unassigned) {
  var sheet = ss.getSheetByName('割当不可');
  if (!sheet) {
    sheet = ss.insertSheet('割当不可');
  }
  sheet.clear();
  var headers = ['日付', '曜日', 'patient_id', '患者名', '必要スタッフ数', '未割当枠', '理由'];
  sheet.getRange(1, 1, 1, headers.length).setValues([headers]);

  if (unassigned.length === 0) return;

  var rows = [];
  for (var i = 0; i < unassigned.length; i++) {
    var u = unassigned[i];
    rows.push([
      u.date_str || u.date || '',
      '',
      u.pid || u.patient_id || '',
      u.pname || u.patient_name || '',
      u.need_staff || 1,
      u.slot || 1,
      u.reason || ''
    ]);
  }
  sheet.getRange(2, 1, rows.length, headers.length).setValues(rows);
}

