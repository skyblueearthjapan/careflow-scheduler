function pyb_timeToMin_(val, tz) {
  if (val === null || val === undefined || val === '') return null;
  if (val instanceof Date) {
    return val.getHours() * 60 + val.getMinutes();
  }
  if (typeof val === 'number') {
    if (val >= 0 && val < 1) return Math.round(val * 24 * 60);
    if (val >= 1 && val < 1440) return Math.round(val);
    return Math.round(val * 24 * 60) % 1440;
  }
  var s = String(val).trim();
  var m = s.match(/(\d{1,2}):(\d{2})/);
  if (m) return parseInt(m[1]) * 60 + parseInt(m[2]);
  return null;
}

function pyb_parseDate_(dateStr) {
  if (!dateStr) return null;
  var parts = String(dateStr).split(/[\/\-]/);
  if (parts.length >= 3) {
    return new Date(parseInt(parts[0]), parseInt(parts[1]) - 1, parseInt(parts[2]));
  }
  return null;
}

function pyb_parseList_(val) {
  if (!val) return [];
  return String(val).split(/[,、\s\/・|]+/).map(function(s) { return s.trim(); }).filter(function(s) { return s; });
}

function pyb_parseDayList_(val) {
  if (!val) return [];
  var items = pyb_parseList_(val);
  var dayMap = {'月':'Mon','火':'Tue','水':'Wed','木':'Thu','金':'Fri','土':'Sat','日':'Sun'};
  return items.map(function(d) { return dayMap[d] || d; });
}

function pyb_normalizeWeekday_(val) {
  if (!val) return '';
  var s = String(val).trim();
  var dayMap = {'月':'Mon','火':'Tue','水':'Wed','木':'Thu','金':'Fri','土':'Sat','日':'Sun',
    'Mon':'Mon','Tue':'Tue','Wed':'Wed','Thu':'Thu','Fri':'Fri','Sat':'Sat','Sun':'Sun'};
  return dayMap[s] || s;
}
