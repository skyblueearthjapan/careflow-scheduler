function pyb_loadStaffMasters_(ss, tz) {
  var sheet = ss.getSheetByName('スタッフマスタ');
  if (!sheet) return [];
  var data = sheet.getDataRange().getValues();
  if (data.length < 2) return [];
  var h = data[0];

  function fc(name) {
    for (var i = 0; i < h.length; i++) {
      if (String(h[i]).indexOf(name) >= 0) return i;
    }
    return -1;
  }

  var ci = {
    id: fc('staff_id'), name: fc('スタッフ名'), gender: fc('性別'),
    lat: fc('緯度'), lng: fc('経度'),
    shiftS: fc('シフト開始'), shiftE: fc('シフト終了'),
    days: fc('勤務曜日'), areas: fc('得意エリア'),
    maxPer: fc('最大訪問件数'), alloc: fc('割当量')
  };

  var results = [];
  for (var i = 1; i < data.length; i++) {
    var r = data[i];
    var sid = ci.id >= 0 ? String(r[ci.id] || '') : '';
    if (!sid) continue;
    results.push({
      staff_id: sid,
      staff_name: ci.name >= 0 ? String(r[ci.name] || '') : '',
      gender: ci.gender >= 0 ? String(r[ci.gender] || '') : '',
      latitude: ci.lat >= 0 ? (r[ci.lat] || null) : null,
      longitude: ci.lng >= 0 ? (r[ci.lng] || null) : null,
      shift_start_minutes: ci.shiftS >= 0 ? pyb_timeToMin_(r[ci.shiftS], tz) || 540 : 540,
      shift_end_minutes: ci.shiftE >= 0 ? pyb_timeToMin_(r[ci.shiftE], tz) || 1080 : 1080,
      work_days: ci.days >= 0 ? pyb_parseDayList_(r[ci.days]) : [],
      areas: ci.areas >= 0 ? pyb_parseList_(r[ci.areas]) : [],
      max_per_day: ci.maxPer >= 0 ? (Number(r[ci.maxPer]) || 999) : 999,
      alloc_pref: ci.alloc >= 0 ? String(r[ci.alloc] || '均等') : '均等'
    });
  }
  return results;
}

