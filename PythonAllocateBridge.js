/**
 * PythonAllocateBridge.js
 * GAS → Python割当エンジン連携
 *
 * Public functions:
 *   - runPythonAllocate(weekStartStr) - メイン実行関数
 */

/**
 * Python割当エンジンでスケジュールを生成する。
 * 既存のGAS割当ロジックとは独立して動作。
 * @param {string} weekStartStr - 週開始日 "yyyy/MM/dd"
 * @returns {Object} {success, message, assigned, unassigned}
 */
function runPythonAllocate(weekStartStr) {
  try {
    var ss = SpreadsheetApp.openById(SPREADSHEET_ID);
    var tz = ss.getSpreadsheetTimeZone();

    if (!weekStartStr) {
      throw new Error('週開始日を指定してください');
    }

    // ============================================================
    // 1. Collect data from sheets
    // ============================================================

    // 1a. Staff masters
    var staffMasters = pyb_loadStaffMasters_(ss, tz);

    // 1b. Patient masters
    var patientMasters = pyb_loadPatientMasters_(ss, tz);

    // 1c. Weekly requests (already generated by GAS)
    var weeklyRequests = pyb_loadWeeklyRequests_(ss, tz, weekStartStr);

    // 1d. Events
    var events = pyb_loadEvents_(ss, tz, weekStartStr);

    // 1e. Staff changes
    var staffChanges = pyb_loadStaffChanges_(ss, tz, weekStartStr);

    // 1f. Weekly patterns (from new pattern editor)
    var weeklyPatterns = pyb_loadWeeklyPatterns_(ss, tz);

    // 1g. Confirmed history (for rotation)
    var confirmedHistory = pyb_loadConfirmedHistory_(ss, tz, weekStartStr);

    // ============================================================
    // 2. Send to Python API
    // ============================================================
    var payload = {
      week_start: weekStartStr,
      staff_masters: staffMasters,
      patient_masters: patientMasters,
      weekly_requests: weeklyRequests,
      events: events,
      staff_changes: staffChanges,
      weekly_patterns: weeklyPatterns,
      confirmed_history: confirmedHistory
    };

    var url = API_BASE_URL + '/api/allocate';
    var options = {
      method: 'post',
      contentType: 'application/json',
      payload: JSON.stringify(payload),
      muteHttpExceptions: true
    };

    console.log('Python割当エンジン呼び出し: ' + weeklyRequests.length + '件のリクエスト');
    var response = UrlFetchApp.fetch(url, options);
    var statusCode = response.getResponseCode();
    var result = JSON.parse(response.getContentText());

    if (statusCode !== 200 || !result.success) {
      return {
        success: false,
        message: 'Python割当エラー: ' + (result.error || result.message || 'HTTP ' + statusCode)
      };
    }

    // ============================================================
    // 3. Write results to 割当結果 sheet
    // ============================================================
    var assignmentResults = result.result.assignment_results || [];
    var summary = result.result.summary || {};

    pyb_writeAssignmentResults_(ss, tz, assignmentResults);

    // Also write unassigned report
    var unassigned = result.result.unassigned || [];
    pyb_writeUnassigned_(ss, tz, unassigned);

    return {
      success: true,
      message: summary.message || ('割当完了: ' + assignmentResults.length + '件'),
      assigned: summary.assigned || 0,
      unassigned: summary.unassigned || 0
    };

  } catch (e) {
    console.error('runPythonAllocate error: ' + e.message);
    return { success: false, message: 'エラー: ' + e.message };
  }
}

